module main

// gen_hyphen reads tools/hyphen_patterns.txt and writes ucd/ucd_hyphen.v,
// the US-English hyphenation patterns layout/hyphen.v hyphenates with.
//
// Everything it emits is plain data: one Liang pattern per line, read back
// with a split on newlines. Keeping the table as text keeps a few dozen
// rows reviewable in a diff, the way the UCD range tables are.
//
// The source table is hand-authored for harfara (MIT); see
// tools/hyphen_patterns.txt for the source note and for why the TeX ushyph
// tables were evaluated and not committed.
//
// Usage: v run tools/gen_hyphen.v
//
// The output is deterministic: rows are trimmed, comment and blank lines
// are dropped, the set is sorted and de-duplicated, and the file ends with
// exactly one newline, so running the generator twice yields byte-identical
// output.

import os

const src_file = 'tools/hyphen_patterns.txt'
const out_file = 'ucd/ucd_hyphen.v'

fn main() {
	src := os.read_file(src_file) or { panic('cannot read ${src_file}: ${err.msg()}') }
	mut seen := map[string]bool{}
	mut rows := []string{}
	for line in src.split_into_lines() {
		t := line.trim_space()
		if t == '' || t.starts_with('#') {
			continue
		}
		if t in seen {
			continue
		}
		seen[t] = true
		rows << t
	}
	if rows.len == 0 {
		panic('${src_file} held no pattern rows')
	}
	rows.sort()
	mut body := 'module ucd\n\n'
	body += '// Code generated by tools/gen_hyphen.v. DO NOT EDIT.\n'
	body += '// Source: tools/hyphen_patterns.txt (hand-authored US-English subset for harfara, MIT)\n'
	body += '// See tools/hyphen_patterns.txt for the source note and the ushyph evaluation.\n\n'
	body += '// hyphen_patterns_data lists the US-English hyphenation patterns in Liang form.\n'
	body += '// Format: one pattern per line (letters with interleaved levels, dot anchors an edge).\n'
	body += '// Odd levels allow a break, even levels suppress one. Sorted and de-duplicated on emission.\n'
	body += "pub const hyphen_patterns_data = '"
	for r in rows {
		body += '${r}\n'
	}
	body += "'\n"
	body = body.trim_right('\n') + '\n'
	os.write_file(out_file, body) or { panic('cannot write ${out_file}: ${err}') }
	println('wrote ${out_file} (${rows.len} patterns, ${body.len} bytes)')
}
