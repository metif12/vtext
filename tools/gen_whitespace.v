module main

// gen_whitespace reads the White_Space property out of ucd/PropList.txt and
// writes ucd/ucd_whitespace.v, the range table the log-attr pass asks whether
// a character is white space with.
//
// Everything it emits is plain data in the established generated-table form:
// one range per line, "lo hi value" in hex and decimal, read back with
// ucd.parse_ranges. Only White_Space rows are emitted (value 1; absent reads
// as 0, not white space), sorted and coalesced so a binary search needs them
// in order.
//
// Usage: v run tools/gen_whitespace.v (run from the module root, after
// tools/fetch_ucd.v has placed PropList.txt under ucd/).
//
// The output is deterministic: the input rows are sorted by codepoint and
// merged, and the file ends with exactly one newline, so running the
// generator twice yields byte-identical output.

import os

const src_file = 'ucd/PropList.txt'
const out_file = 'ucd/ucd_whitespace.v'

struct WsRange {
mut:
	lo u32
	hi u32
}

fn parse_ws_hex(s string) u32 {
	mut n := u32(0)
	for c in s {
		mut d := u32(0)
		if c >= `0` && c <= `9` {
			d = u32(c - `0`)
		} else if c >= `A` && c <= `F` {
			d = u32(c - `A`) + 10
		} else if c >= `a` && c <= `f` {
			d = u32(c - `a`) + 10
		} else {
			panic('bad hex digit in ${s}')
		}
		n = n * 16 + d
	}
	return n
}

fn main() {
	src := os.read_file(src_file) or { panic('cannot read ${src_file}: ${err.msg()}') }
	mut ranges := []WsRange{}
	for line in src.split_into_lines() {
		t := line.split('#')[0].trim_space()
		if t == '' {
			continue
		}
		parts := t.split(';')
		if parts.len != 2 || parts[1].trim_space() != 'White_Space' {
			continue
		}
		bounds := parts[0].trim_space().split('..')
		lo := parse_ws_hex(bounds[0].trim_space())
		mut hi := lo
		if bounds.len == 2 {
			hi = parse_ws_hex(bounds[1].trim_space())
		}
		if hi < lo {
			panic('inverted range in ${src_file}: ${t}')
		}
		ranges << WsRange{ lo: lo, hi: hi }
	}
	if ranges.len == 0 {
		panic('${src_file} held no White_Space rows. Run tools/fetch_ucd.v first.')
	}
	ranges.sort_with_compare(fn (a &WsRange, b &WsRange) int {
		if a.lo < b.lo {
			return -1
		}
		if a.lo > b.lo {
			return 1
		}
		return 0
	})
	// Coalesce adjacent and overlapping rows; the UCD groups by property,
	// not by codepoint, and lists singletons beside ranges.
	mut merged := []WsRange{}
	for r in ranges {
		if merged.len > 0 {
			mut tail := merged[merged.len - 1]
			if r.lo <= tail.hi + 1 {
				if r.hi > tail.hi {
					tail.hi = r.hi
				}
				merged[merged.len - 1] = tail
				continue
			}
		}
		merged << r
	}
	mut body := 'module ucd\n\n'
	body += '// Code generated by tools/gen_whitespace.v. DO NOT EDIT.\n'
	body += '// Source: Unicode Character Database 18.0.0, PropList.txt (White_Space only)\n\n'
	body += '// whitespace_ranges_data gives the White_Space property of every codepoint.\n'
	body += '// Format: one range per line, "lo hi value" in hex and decimal; value 1 is\n'
	body += '// white space, and an absent codepoint reads as 0, not white space.\n'
	body += "pub const whitespace_ranges_data = '"
	for r in merged {
		body += '${r.lo:04x} ${r.hi:04x} 1\n'
	}
	body += "'\n"
	body = body.trim_right('\n') + '\n'
	os.write_file(out_file, body) or { panic('cannot write ${out_file}: ${err}') }
	println('wrote ${out_file} (${merged.len} ranges, ${body.len} bytes)')
}
