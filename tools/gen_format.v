module main

// gen_format reads General_Category=Cf out of ucd/UnicodeData.txt and writes
// ucd/ucd_format.v, the range table the joining pass asks whether a
// transparent zero-class character is an invisible format control with.
//
// Everything it emits is plain data in the established generated-table form:
// one range per line, "lo hi value" in hex and decimal, read back with
// ucd.parse_ranges. Only Cf rows are emitted (value 1; absent reads as 0,
// not a format character), sorted and coalesced so a binary search needs
// them in order.
//
// Usage: v run tools/gen_format.v (run from the module root, after
// tools/fetch_ucd.v has placed UnicodeData.txt under ucd/).
//
// The output is deterministic: the input rows are sorted by codepoint and
// merged, and the file ends with exactly one newline, so running the
// generator twice yields byte-identical output.

import os

const src_file = 'ucd/UnicodeData.txt'
const out_file = 'ucd/ucd_format.v'

struct FmtRange {
mut:
	lo u32
	hi u32
}

fn parse_fmt_hex(s string) u32 {
	mut n := u32(0)
	for c in s {
		mut d := u32(0)
		if c >= `0` && c <= `9` {
			d = u32(c - `0`)
		} else if c >= `A` && c <= `F` {
			d = u32(c - `A`) + 10
		} else if c >= `a` && c <= `f` {
			d = u32(c - `a`) + 10
		} else {
			panic('bad hex digit in ${s}')
		}
		n = n * 16 + d
	}
	return n
}

fn main() {
	src := os.read_file(src_file) or { panic('cannot read ${src_file}: ${err.msg()}') }
	mut ranges := []FmtRange{}
	for line in src.split_into_lines() {
		t := line.split('#')[0].trim_space()
		if t == '' {
			continue
		}
		// UnicodeData.txt is semicolon-separated with the general category
		// third: codepoint;name;Cf;.... Surrogates and private-use lines
		// never carry Cf, so no exclusion is needed.
		parts := t.split(';')
		if parts.len < 3 || parts[2].trim_space() != 'Cf' {
			continue
		}
		lo := parse_fmt_hex(parts[0].trim_space())
		ranges << FmtRange{ lo: lo, hi: lo }
	}
	if ranges.len == 0 {
		panic('${src_file} held no Cf rows. Run tools/fetch_ucd.v first.')
	}
	ranges.sort_with_compare(fn (a &FmtRange, b &FmtRange) int {
		if a.lo < b.lo {
			return -1
		}
		if a.lo > b.lo {
			return 1
		}
		return 0
	})
	// Coalesce adjacent and overlapping rows; UnicodeData lists singletons.
	mut merged := []FmtRange{}
	for r in ranges {
		if merged.len > 0 {
			mut tail := merged[merged.len - 1]
			if r.lo <= tail.hi + 1 {
				if r.hi > tail.hi {
					tail.hi = r.hi
				}
				merged[merged.len - 1] = tail
				continue
			}
		}
		merged << r
	}
	mut body := 'module ucd\n\n'
	body += '// Code generated by tools/gen_format.v. DO NOT EDIT.\n'
	body += '// Source: Unicode Character Database 18.0.0, UnicodeData.txt (General_Category=Cf only)\n\n'
	body += '// format_ranges_data gives the Format (Cf) general category of every codepoint.\n'
	body += '// Format: one range per line, "lo hi value" in hex and decimal; value 1 is\n'
	body += '// a format character, and an absent codepoint reads as 0, not one.\n'
	body += "pub const format_ranges_data = '"
	for r in merged {
		body += '${r.lo:04x} ${r.hi:04x} 1\n'
	}
	body += "'\n"
	os.write_file(out_file, body) or { panic('cannot write ${out_file}: ${err.msg()}') }
	println('wrote ${out_file}: ${merged.len} ranges from ${ranges.len} Cf rows')
}
